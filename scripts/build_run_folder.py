def build():
    if DEST.exists():
        shutil.rmtree(DEST)
    for folder, notebooks in STEPS:
        (DEST / folder).mkdir(parents=True, exist_ok=True)
        for name in notebooks or []:
            shutil.copy2(SRC / name, DEST / folder / name)
    labels = ROOT / 'reader_labels'
    if labels.is_dir():
        shutil.copytree(labels, DEST / 'step1_upload_dataset' / 'reader_labels')
    wheels = ROOT / 'wheelhouse_upload'          # timm, pydicom, pylibjpeg* for Linux cp313
    if wheels.is_dir():
        shutil.copytree(wheels, DEST / 'step1_upload_dataset' / 'knee_wheelhouse')
    (DEST / 'README.md').write_text(README)


if __name__ == '__main__':
    build()
